// The customer tiers (chat-only product): validation, the generated config, and the audited model change.
//
//   node content/tiers.mjs check [--prices deploy/staging/iqraa.json]
//   node content/tiers.mjs apply --resolved <resolved.json> --yaml <librechat.yaml> --iqraa <iqraa.json>
//   node content/tiers.mjs specs --resolved <resolved.json>
//   node content/tiers.mjs set-model <key> <provider> <model> --note "<why>" [--prices <iqraa.json>] [--actor <name>]
//
// `content/tiers.json` is the source of record (reviewed, versioned): each tier's name, description, plans and the
// internal provider/model that serves it. `release.mjs` creates one private agent per tier and writes a resolved
// file ({ tiers: [{ key, spec, agentId }] }); `apply` then writes the matching `modelSpecs` block into
// librechat.yaml (between the BEGIN/END markers) and the `tiers` block into iqraa.json, and a restart picks both up.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
export const TIERS_FILE = path.join(here, 'tiers.json');
export const AUDIT_FILE = path.join(here, 'tiers.audit.jsonl');
export const BEGIN = '# BEGIN iqraa:modelSpecs (generated by content/tiers.mjs apply; do not edit by hand)';
export const END = '# END iqraa:modelSpecs';

const KEY = /^[a-z]+$/;

/** Problems with the tier table, as readable lines; empty when it is valid. */
export function validateTiers(doc, { roles, prices } = {}) {
  const errors = [];
  const tiers = doc?.tiers;
  if (doc?.version !== 1 || !Array.isArray(tiers) || tiers.length === 0) {
    return ['tiers.json needs version 1 and a non-empty tiers list'];
  }
  const keys = new Set();
  const orders = new Set();
  for (const tier of tiers) {
    const at = `tier ${tier.key}`;
    if (!KEY.test(tier.key ?? '')) errors.push(`${at}: key must be lowercase letters`);
    if (keys.has(tier.key)) errors.push(`${at}: key used twice`);
    keys.add(tier.key);
    if (tier.spec !== `iqraa-${tier.key}`) errors.push(`${at}: spec must be iqraa-${tier.key}`);
    if (!tier.label?.trim()) errors.push(`${at}: label is empty`);
    if (!tier.description?.trim()) errors.push(`${at}: description is empty`);
    if (!Number.isInteger(tier.order)) errors.push(`${at}: order must be an integer`);
    if (orders.has(tier.order)) errors.push(`${at}: order used twice`);
    orders.add(tier.order);
    if (!Array.isArray(tier.plans) || tier.plans.length === 0) errors.push(`${at}: plans is empty`);
    for (const plan of tier.plans ?? []) {
      if (roles && !(plan in roles)) errors.push(`${at}: plan ${plan} is not a role in roles.json`);
    }
    if (!tier.provider || !tier.model) errors.push(`${at}: provider and model are required`);
    if (prices && tier.model && !(tier.model in prices)) {
      errors.push(`${at}: model ${tier.model} has no price (metering would refuse it)`);
    }
  }
  const first = [...tiers].sort((a, b) => a.order - b.order)[0];
  const everyPlan = new Set(tiers.flatMap((tier) => tier.plans ?? []));
  for (const plan of everyPlan) {
    if (!first.plans?.includes(plan)) {
      errors.push(`tier ${first.key} is the default and must include every plan (${plan} is missing)`);
    }
  }
  return errors;
}

/** The modelSpecs block for the resolved tiers; the first tier by order is the default. */
export function specsBlock(doc, resolved) {
  const ids = new Map(resolved.tiers.map((entry) => [entry.key, entry.agentId]));
  const ordered = [...doc.tiers].sort((a, b) => a.order - b.order);
  const lines = [BEGIN, 'modelSpecs:', '  enforce: false', '  prioritize: true'];
  if (ordered.length === 0 || ordered.some((tier) => !ids.has(tier.key))) {
    lines.push('  list: []');
  } else {
    lines.push('  list:');
    ordered.forEach((tier, index) => {
      lines.push(
        `    - name: ${tier.spec}`,
        `      label: ${JSON.stringify(tier.label)}`,
        `      description: ${JSON.stringify(tier.description)}`,
        ...(index === 0 ? ['      default: true'] : []),
        '      preset:',
        '        endpoint: agents',
        `        agent_id: ${ids.get(tier.key)}`,
      );
    });
  }
  lines.push(END);
  return lines.join('\n') + '\n';
}

/** Replaces the marked region of librechat.yaml; throws when the markers are not both there once. */
export function applyToYaml(yamlText, block) {
  const text = yamlText.replace(/\r\n/g, '\n');
  const start = text.indexOf(BEGIN);
  const end = text.indexOf(END);
  if (start === -1 || end === -1 || end < start || text.indexOf(BEGIN, start + 1) !== -1) {
    throw new Error('librechat.yaml needs exactly one BEGIN/END iqraa:modelSpecs region');
  }
  return text.slice(0, start) + block + text.slice(end + END.length).replace(/^\n/, '');
}

/**
 * iqraa.json with its `tiers` set from the tier table (spec and plans only: the private mapping stays here). The
 * fork refuses to start when tiers and model specs differ, and `specsBlock` writes specs only once every tier has an
 * agent, so this writes tiers on the same condition: a fresh stack (no agent yet, or only some) gets none of either.
 */
export function applyToIqraa(iqraa, doc, resolved) {
  const known = new Set(resolved.tiers.map((entry) => entry.key));
  const complete = doc.tiers.every((tier) => known.has(tier.key));
  const tiers = complete
    ? [...doc.tiers].sort((a, b) => a.order - b.order).map((tier) => ({ spec: tier.spec, plans: tier.plans }))
    : [];
  return { ...iqraa, tiers };
}

/** A copy of the table with one tier's model changed, and the audit row that records it. */
export function setModel(doc, { key, provider, model, note, actor, prices, now = new Date() }) {
  const tier = doc.tiers.find((entry) => entry.key === key);
  if (!tier) throw new Error(`no tier ${key}`);
  if (!note?.trim()) throw new Error('--note is required: say why the model changes');
  if (prices && !(model in prices)) throw new Error(`model ${model} has no price in the prices file`);
  const row = {
    ts: now.toISOString(),
    tier: key,
    actor: actor ?? process.env.USERNAME ?? process.env.USER ?? 'unknown',
    from: { provider: tier.provider, model: tier.model },
    to: { provider, model },
    note: note.trim(),
  };
  const next = { ...doc, tiers: doc.tiers.map((entry) => (entry.key === key ? { ...entry, provider, model } : entry)) };
  return { doc: next, row };
}

const readJson = (file) => JSON.parse(fs.readFileSync(file, 'utf8'));
const flag = (args, name) => {
  const at = args.indexOf(name);
  return at === -1 ? undefined : args[at + 1];
};

function main(args) {
  const [command, ...rest] = args;
  const doc = readJson(TIERS_FILE);
  const roles = readJson(path.join(here, 'roles.json'));
  const pricesFile = flag(rest, '--prices');
  const prices = pricesFile ? readJson(pricesFile).prices : undefined;
  if (command === 'check') {
    const errors = validateTiers(doc, { roles, prices });
    if (errors.length > 0) {
      console.error(errors.join('\n'));
      process.exit(1);
    }
    console.log(`tiers ok: ${doc.tiers.map((tier) => tier.key).join(', ')}`);
  } else if (command === 'specs') {
    process.stdout.write(specsBlock(doc, readJson(flag(rest, '--resolved'))));
  } else if (command === 'apply') {
    const resolved = readJson(flag(rest, '--resolved'));
    const yamlFile = flag(rest, '--yaml');
    const iqraaFile = flag(rest, '--iqraa');
    const yaml = applyToYaml(fs.readFileSync(yamlFile, 'utf8'), specsBlock(doc, resolved));
    const iqraa = JSON.stringify(applyToIqraa(readJson(iqraaFile), doc, resolved), null, 2) + '\n';
    const changed = yaml !== fs.readFileSync(yamlFile, 'utf8').replace(/\r\n/g, '\n') || iqraa !== fs.readFileSync(iqraaFile, 'utf8');
    fs.writeFileSync(yamlFile, yaml);
    fs.writeFileSync(iqraaFile, iqraa);
    console.log(changed ? 'changed: restart librechat to load the tiers' : 'unchanged');
  } else if (command === 'set-model') {
    const [key, provider, model] = rest;
    const { doc: next, row } = setModel(doc, { key, provider, model, note: flag(rest, '--note'), actor: flag(rest, '--actor'), prices });
    fs.writeFileSync(TIERS_FILE, JSON.stringify(next, null, 2) + '\n');
    fs.appendFileSync(AUDIT_FILE, JSON.stringify(row) + '\n');
    console.log(`tier ${key}: ${row.from.provider}/${row.from.model} -> ${provider}/${model}; run content/release.mjs to apply it`);
  } else {
    console.error('usage: tiers.mjs check | specs | apply | set-model (see the header)');
    process.exit(2);
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(`tiers: ${error.message}`);
    process.exit(1);
  }
}
